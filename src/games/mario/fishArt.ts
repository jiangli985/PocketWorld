type PixelRun = readonly [x: number, y: number, length: number];
type RasterSprite = ReadonlyMap<string, readonly PixelRun[]>;
const sprites = new Map<FishId, RasterSprite>();

function toneColor(palette: Palette, tone: Tone) {
  if (tone === 'ink') return ink;
  if (tone === 'glint') return glint;
  return palette[tone];
}

function rasterize({ palette, shapes, eye: [eyeX, eyeY], marks }: Sprite): RasterSprite {
  const pixels = new Array<string | undefined>(width * height);
  for (const [tone, ...vertices] of shapes) {
    const color = toneColor(palette, tone);
    for (let y = 0; y < height; y++) {
      const scan = y + .5;
      const crossings: number[] = [];
      for (let i = 0, j = vertices.length - 2; i < vertices.length; j = i, i += 2) {
        const y1 = vertices[i + 1], y2 = vertices[j + 1];
        if ((y1 > scan) === (y2 > scan)) continue;
        const x1 = vertices[i], x2 = vertices[j];
        crossings.push(x1 + (x2 - x1) * (scan - y1) / (y2 - y1));
      }
      crossings.sort((a, b) => a - b);
      for (let i = 0; i < crossings.length; i += 2) {
        const first = Math.max(0, Math.ceil(crossings[i] - .5));
        const end = Math.min(width, Math.ceil(crossings[i + 1] - .5));
        for (let x = first; x < end; x++) pixels[y * width + x] = color;
      }
    }
  }

  const edged = pixels.slice();
  for (let y = 1; y < height - 1; y++) {
    for (let x = 1; x < width - 1; x++) {
      const i = y * width + x;
      if (!pixels[i] && (pixels[i - 1] || pixels[i + 1] || pixels[i - width] || pixels[i + width])) edged[i] = ink;
    }
  }

  const details: readonly Mark[] = [
    ...(marks ?? []),
    ['glint', eyeX - 1, eyeY - 1, 3, 3],
    ['ink', eyeX, eyeY, 2, 2],
  ];
  for (const [tone, x, y, w = 1, h = 1] of details) {
    const color = toneColor(palette, tone);
    for (let dy = 0; dy < h; dy++) {
      for (let dx = 0; dx < w; dx++) edged[(y + dy) * width + x + dx] = color;
    }
  }

  const runs = new Map<string, PixelRun[]>();
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width;) {
      const color = edged[y * width + x];
      let end = x + 1;
      while (end < width && edged[y * width + end] === color) end++;
      if (color) {
        const line: PixelRun = [x, y, end - x];
        const strokes = runs.get(color);
        if (strokes) strokes.push(line);
        else runs.set(color, [line]);
      }
      x = end;
    }
  }
  return runs;
}

export function drawFish(context: CanvasRenderingContext2D, id: FishId) {
  let sprite = sprites.get(id);
  if (!sprite) {
    sprite = rasterize(fishArt[id]);
    sprites.set(id, sprite);
  }
  for (const [color, runs] of sprite) {
    context.fillStyle = color;
    for (const [x, y, length] of runs) context.fillRect(x, y, length, 1);
  }
}
