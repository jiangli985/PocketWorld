export type BoatControlId = keyof typeof controls;
export type FishingIconId = keyof typeof art;

export function drawFishingIcon(canvas: HTMLCanvasElement, id: FishingIconId) {
  const context = canvas.getContext('2d');
  if (!context) return;
  context.clearRect(0, 0, FISHING_ICON_SIZE, FISHING_ICON_SIZE);
  const layers: readonly PixelLayer[] = art[id];
  for (const [color, ...blocks] of layers) {
    context.fillStyle = color;
    for (const block of blocks) context.fillRect(...block);
  }
}
