const signs = [
  { label: '渔具店', center: 128, top: 129, spacing: 4, lamps: [98, 153], base: [171, 153, 112] },
  { label: '深海渔场大排档', center: 285, top: 129, spacing: 2, lamps: [249, 318], base: [197, 145, 97] },
] as const;

/** Paint the plaques in the street image's 400 × 300 coordinate space. */
export function paintDockSigns(context: CanvasRenderingContext2D) {
  for (const sign of signs) {
    const advance = 13 + sign.spacing;
    const left = Math.round(sign.center - (sign.label.length * advance - sign.spacing) / 2);
    const pixels: Array<[number, number]> = [];
    Array.from(sign.label).forEach((character, index) => {
      glyphs[character as keyof typeof glyphs].forEach((row, y) => {
        for (let x = 0; x < row.length; x++) {
          if (row[x] === '#') pixels.push([left + index * advance + x, sign.top + y]);
        }
      });
    });

    context.fillStyle = '#151a26a6';
    for (const [x, y] of pixels) context.fillRect(x + 1, y + 1, 1, 1);
    for (const [x, y] of pixels) {
      const lampDistance = Math.min(Math.abs(x - sign.lamps[0]), Math.abs(x - sign.lamps[1]));
      const light = Math.round(Math.max(0, 43 - lampDistance - 2 * (y - sign.top)));
      const [red, green, blue] = sign.base;
      context.fillStyle = `rgb(${red + light}, ${green + light}, ${blue + light})`;
      context.fillRect(x, y, 1, 1);
    }
  }
}
