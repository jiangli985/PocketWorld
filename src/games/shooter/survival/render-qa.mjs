import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const here=path.dirname(fileURLToPath(import.meta.url));
const require=createRequire(path.join(process.argv[2]??path.resolve(here,'../../../..'),'package.json'));
const {buildSync}=require('esbuild');
const runtimeRequire=createRequire(process.execPath);
const {createCanvas}=runtimeRequire('@napi-rs/canvas');
buildSync({entryPoints:[path.join(here,'render.ts')],bundle:true,platform:'node',format:'cjs',outfile:path.join(here,'dist/render.cjs')});
const {render}=require(path.join(here,'dist/render.cjs'));
const {createRun,advance,ARSENAL}=require(path.join(here,'dist/engine.cjs'));
const run=createRun(()=>.42,'wand');
run.time=125;run.specials.twin=2;run.specials.sigil=2;run.enchants.wand.frost=1;run.enchants.wand.chain=1;
run.enemies=Array.from({length:16},(_,i)=>{const a=i*Math.PI*2/16,d=120+(i%3)*50;return {id:i+1,x:1000+Math.cos(a)*d,y:1000+Math.sin(a)*d,kind:i%7===0?2:i%3===0?1:0,hp:150,max:150,radius:18,speed:20,seed:i,flash:0,hit:0,charge:4};});
for(let i=0;i<90;i++){run.invincible=1;advance(run,1/60);run.sounds.length=0;}
const battle=createCanvas(800,600),low=createCanvas(640,480);
run.invincible=0;
render(battle.getContext('2d'),run,false,run.time,low);
fs.writeFileSync(path.join(here,'dist/像素魔法战斗预览.png'),battle.toBuffer('image/png'));
const home=createCanvas(800,600);render(home.getContext('2d'),createRun(()=>.4,'broom'),true,4,low);
fs.writeFileSync(path.join(here,'dist/像素魔法场景预览.png'),home.toBuffer('image/png'));
for(const id of ['pistol','machine','rocket','wand','broom'])render(battle.getContext('2d'),createRun(()=>.4,id),true,3,low);
for(const a of ARSENAL)render(battle.getContext('2d'),createRun(()=>.4,a.family,a.id),true,3,low,2);
if(low.width!==640||low.height!==480)throw new Error('HD scene resolution mismatch');
render(battle.getContext('2d'),run,false,run.time,low,1);
if(low.width!==320||low.height!==240)throw new Error('Classic scene resolution mismatch');
console.log('Rendered 15 armaments and verified HD 640×480 / classic 320×240 surfaces.');
