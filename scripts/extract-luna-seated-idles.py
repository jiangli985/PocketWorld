"""Extract the Luna seated idle curves from the 120 Hz CMU 13_04 and 01_06 takes.

Run: python3 scripts/extract-luna-seated-idles.py <directory containing both AMC files>
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SAMPLE_STEP = 12


def read_take(path):
    frames = []
    for line in path.read_text().splitlines():
        fields = line.split()
        if not fields or fields[0][0] in '#:':
            continue
        if fields[0].isdigit():
            frames.append({})
        else:
            frames[-1][fields[0]] = [float(value) for value in fields[1:]]
    return frames


def samples(frames, first, last):
    return frames[first - 1:last:SAMPLE_STEP]


def rows(name, values):
    return f'export const {name} = [\n' + ''.join(
        '  ' + ', '.join(f'{value:.4f}' for value in row) + ',\n'
        for row in values
    ) + '] as const;\n'


directory = Path(sys.argv[1])
sofa_take = read_take(directory / '13_04.amc')
# Slow the quick hand release while keeping the original trajectory.
sofa = samples(sofa_take, 1573, 2088) + sofa_take[2088:2149:5]
chair = samples(read_take(directory / '01_06.amc'), 985, 1357)
# Elbow flexion gives the timing of the left hand moving up, settling, and leaving.
# Limit the hold to one so torso and palm stay correctly fitted to Luna.
reach = [(max(0., min(1., (frame['lradius'][0] - 68) / 60)),
          (frame['head'][1] - sofa[19]['head'][1]) / 180)
         for frame in sofa]
# Preserve the relative phase and asymmetric speed but fit the arc to the chair.
shin = [tuple((frame[side + 'tibia'][0] - 66) / 160 for side in ('l', 'r')) for frame in chair]
output = ('// Generated by scripts/extract-luna-seated-idles.py from CMU 13_04 and 01_06.\n'
          '// Interleaved samples at 10 Hz. See assets/models/resident/README.md for provenance.\n'
          'export const SEATED_IDLE_FPS = 10;\n'
          '// Left elbow reach and head yaw (radians).\n'
          + rows('SOFA_CHEEK_REST', reach)
          + '// Left and right knee flexion offsets (radians).\n'
          + rows('CHAIR_LEG_SWING', shin))
(ROOT / 'src/scene/orbital/seatedIdleFrames.ts').write_text(output)
